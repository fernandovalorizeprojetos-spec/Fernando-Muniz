CREATE TABLE IF NOT EXISTS projetos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  subtitulo TEXT NOT NULL,
  descricao TEXT NOT NULL,
  data_inicio DATE NOT NULL,
  data_fim DATE NOT NULL,
  valor_global NUMERIC(12, 2) NOT NULL CHECK (valor_global >= 0),
  publico_direto INTEGER NOT NULL CHECK (publico_direto >= 0),
  horas_oficinas INTEGER NOT NULL CHECK (horas_oficinas >= 0),
  horas_queimas INTEGER NOT NULL CHECK (horas_queimas >= 0),
  contato TEXT NOT NULL,
  metodologia JSONB NOT NULL DEFAULT '[]'::jsonb,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS metricas (
  id TEXT PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  rotulo TEXT NOT NULL,
  valor NUMERIC(12, 2) NOT NULL CHECK (valor >= 0),
  unidade TEXT NOT NULL DEFAULT '',
  formato TEXT NOT NULL CHECK (formato IN ('currency', 'number', 'hours', 'months')),
  detalhe TEXT NOT NULL DEFAULT '',
  icone TEXT NOT NULL DEFAULT 'modules',
  posicao INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS cronograma (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  duracao_meses INTEGER NOT NULL CHECK (duracao_meses >= 0),
  descricao TEXT NOT NULL DEFAULT '',
  atividades JSONB NOT NULL DEFAULT '[]'::jsonb,
  posicao INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS equipe (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  qualificacao TEXT NOT NULL DEFAULT '',
  funcao TEXT NOT NULL DEFAULT '',
  responsabilidades TEXT NOT NULL DEFAULT '',
  posicao INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS modulos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  numero INTEGER NOT NULL CHECK (numero > 0),
  nome TEXT NOT NULL,
  horas INTEGER NOT NULL CHECK (horas >= 0),
  descricao TEXT NOT NULL DEFAULT '',
  atividades JSONB NOT NULL DEFAULT '[]'::jsonb,
  posicao INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS acessibilidade (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL,
  descricao TEXT NOT NULL DEFAULT '',
  itens JSONB NOT NULL DEFAULT '[]'::jsonb,
  posicao INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS decisoes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  projeto_id INTEGER NOT NULL REFERENCES projetos(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL,
  descricao TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Resolvido',
  posicao INTEGER NOT NULL DEFAULT 0
);
